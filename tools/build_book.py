#!/usr/bin/env python3
"""Verify each repertoire line with a reference engine and emit src/gambits.inc.

For every line we evaluate each position from ply MIN_PLY onward. The line is trimmed to the last
position where the gambiteer is no worse than HARD_FLOOR and no better than CEILING (a very high plus score
means the scripted opponent move was a mistake we should not force the game into). The worst evaluation seen
inside the kept prefix is stored as the line's "deficit" so the engine's GambitRisk option can filter at runtime.
Verification happens at book-construction time only; the shipped binary contains no Stockfish code.
"""
import chess, chess.engine, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from repertoire import REPERTOIRE

SF = os.environ.get("SF", "/tmp/sf/sf")
HARD_FLOOR = int(os.environ.get("HARD_FLOOR", "-110"))
CEILING = int(os.environ.get("CEILING", "160"))
MIN_PLY = 7
NODES = int(os.environ.get("NODES", "600000"))
out_path = os.path.join(os.path.dirname(__file__), "..", "src", "gambits.inc")

eng = chess.engine.SimpleEngine.popen_uci(SF)
eng.configure({"Threads": 2, "Hash": 256})
report, lines = [], []
for name, col, weight, san in REPERTOIRE:
    b = chess.Board(); moves = []; ok = True
    for tok in san.split():
        try: mv = b.parse_san(tok)
        except Exception: ok = False; report.append((name, "ILLEGAL " + tok)); break
        moves.append(mv); b.push(mv)
    if not ok: continue
    us = chess.WHITE if col == "w" else chess.BLACK
    b = chess.Board(); evals = {}
    for i, mv in enumerate(moves, 1):
        was_cap = b.is_capture(mv)   # only score quiet positions: a pending recapture makes evals meaningless
        b.push(mv)
        if i >= MIN_PLY and not b.is_game_over() and not b.is_check() and not (i >= 2 and was_cap):
            evals[i] = eng.analyse(b, chess.engine.Limit(nodes=NODES))["score"].pov(us).score(mate_score=10000)
    cut = 0
    for i in sorted(evals):
        if HARD_FLOOR <= evals[i] <= CEILING: cut = i
    if cut < MIN_PLY or weight <= 0:
        report.append((name, "DROP (no sound prefix)" if weight > 0 else "DROP (weight 0)")); continue
    worst = min(evals[i] for i in evals if i <= cut); worst = min(worst, 0)
    report.append((name, f"keep {cut}/{len(moves)} plies, worst {worst:+d}cp, end {evals[cut]:+d}cp"))
    if -worst > 150: report[-1] = (name, report[-1][1] + '  -> DROP (deficit too large)'); continue
    lines.append((weight, -worst, 1 if col == 'w' else -1, " ".join(m.uci() for m in moves[:cut])))
eng.quit()
with open(out_path, "w") as f:
    f.write("// GENERATED by tools/build_book.py — do not edit by hand.\n// {weight, deficit_cp, side (1=White gambit, -1=Black gambit), uci moves}\n")
    for w, d, c, l in lines: f.write(f'    {{{w}, {d}, {c}, "{l}"}},\n')
txt_path = os.path.join(os.path.dirname(__file__), "..", "book", "athena_gambits.txt")
with open(txt_path, "w") as f:
    f.write("# Athena gambit repertoire. Format: <weight> <deficit_cp> <w|b> <uci moves from the start position>\n")
    f.write("# deficit_cp = worst evaluation (centipawns) the gambit side reaches in the line, checked with a reference engine.\n")
    f.write("# Raise 'GambitRisk' (UCI option) to allow lines with larger deficits. Lines here are ADDED to the built-in book.\n")
    for w, d, c, l in lines: f.write(f"{w} {d} {'w' if c == 1 else 'b'} {l}\n")
for r in report: print(f"{r[0]:70s} {r[1]}")
print(f"\n{len(lines)} of {len(REPERTOIRE)} lines kept")
